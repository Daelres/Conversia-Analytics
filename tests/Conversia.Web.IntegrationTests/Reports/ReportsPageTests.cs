    [Fact]
    public async Task A_person_accepts_and_withdraws_the_reports_on_whatsapp_and_consent_is_required()
    {
        var owner = await ApiSeed.RegisterOwnerAsync(api, "informe-wa");
        using var host = WebTestHost.Create(api);
        using var session = await WebFlows.SignedInAsync(host, owner.Email);

        var page = (await session.GetAsync("/informes/whatsapp")).ShouldBe(HttpStatusCode.OK);
        Assert.Contains("No recibes informes", page.Document.QuerySelector("[data-testid=optin-state]")!.TextContent);
        var withoutConsent = await session.SubmitAsync(FormModel.From(page, Form(page, "optin-form")).Set("PhoneNumber", "+57 311 555 0123"));
        Assert.Contains("aceptar expresamente", withoutConsent.ShouldBe(HttpStatusCode.BadRequest).Document.QuerySelector("[data-testid=optin-problem]")!.TextContent);

        page = (await session.GetAsync("/informes/whatsapp")).ShouldBe(HttpStatusCode.OK);
        var accepted = await session.SubmitAsync(FormModel.From(page, Form(page, "optin-form")).Set("PhoneNumber", "+57 311 555 0123").Add("Input.Consent", "true"));
        // No report template yet in this company: the consent is kept, no code can be sent, and the number receives nothing until it is verified.
        accepted.ShouldRedirectTo("/informes/whatsapp?aviso=sin-codigo");
        var state = (await session.FollowAsync(accepted)).ShouldBe(HttpStatusCode.OK);
        Assert.NotNull(state.Document.QuerySelector("[data-testid=notice-code-not-sent]"));
        Assert.Contains("Falta confirmar +573115550123", state.Document.QuerySelector("[data-testid=optin-state]")!.TextContent);
        Assert.NotNull(state.Document.QuerySelector("[data-testid=optin-verify-form]"));
        var wrong = await session.SubmitAsync(FormModel.From(state, Form(state, "optin-verify-form")).Set("Value", "123456"));
        Assert.Contains("no es válido", wrong.ShouldBe(HttpStatusCode.BadRequest).Document.QuerySelector("[data-testid=optin-problem]")!.TextContent);
        state = (await session.GetAsync("/informes/whatsapp")).ShouldBe(HttpStatusCode.OK);

        (await session.SubmitAsync(FormModel.From(state, Form(state, "optout-form")))).ShouldRedirectTo("/informes/whatsapp?aviso=retirado");
        Assert.Contains("No recibes informes", (await session.GetAsync("/informes/whatsapp")).Document.QuerySelector("[data-testid=optin-state]")!.TextContent);
    }

    [Fact]
    public async Task The_unsubscribe_link_asks_before_it_acts_and_the_one_click_endpoint_works_without_a_session()
    {
        var owner = await ApiSeed.RegisterOwnerAsync(api, "informe-baja");
        var definitionId = await CreateDefinitionAsync(owner, owner.UserId);
        Guid recipientId;
        using (var scope = api.Services.CreateScope())
        {
            recipientId = await scope.ServiceProvider.GetRequiredService<ApplicationDbContext>().ReportRecipients.IgnoreQueryFilters()
                .Where(r => r.DefinitionId == definitionId).Select(r => r.Id).SingleAsync();
        }

        var token = ReportUnsubscribeToken.Create(recipientId, api.Services.GetRequiredService<ReportUnsubscribeKey>().Key);
        using var host = WebTestHost.Create(api);
        using var anonymous = host.NewSession();

        var landing = (await anonymous.GetAsync($"/informes/baja?t={Uri.EscapeDataString(token)}")).ShouldBe(HttpStatusCode.OK);
        Assert.Null(landing.Document.QuerySelector("[data-testid=notice-success]")); // a link scanner that only opens it unsubscribes nobody
        Assert.Empty(SpanishUi.Leaks(SpanishUi.Extract(landing)));
        var done = (await anonymous.SubmitAsync(FormModel.From(landing, Form(landing, "unsubscribe-form")))).ShouldBe(HttpStatusCode.OK);
        Assert.Contains("ya no recibirás «Resumen semanal» por correo", done.Document.QuerySelector("[data-testid=notice-success]")!.TextContent);

        var forged = (await anonymous.GetAsync("/informes/baja?t=AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA")).ShouldBe(HttpStatusCode.OK);
        (await anonymous.SubmitAsync(FormModel.From(forged, Form(forged, "unsubscribe-form")))).ShouldBe(HttpStatusCode.NotFound);

        var oneClick = await anonymous.PostRawAsync($"/informes/baja/un-clic?t={Uri.EscapeDataString(token)}",
            new FormUrlEncodedContent([new KeyValuePair<string, string>("List-Unsubscribe", "One-Click")]));
        oneClick.ShouldBe(HttpStatusCode.OK);
        (await anonymous.PostRawAsync("/informes/baja/un-clic?t=no-es-valido", new FormUrlEncodedContent([]))).ShouldBe(HttpStatusCode.NotFound);
    }

