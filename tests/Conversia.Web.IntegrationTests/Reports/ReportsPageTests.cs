/// <summary>
/// The manager report pages against the real API and database (docs/REPORTS.md): settings, the report page, the preview, the WhatsApp opt-in and
/// the unsubscribe landing (with the one-click endpoint). Reports are generated by the API's job runner, called by hand.
/// </summary>
[Collection(nameof(WebIntegrationCollection))]
public class ReportsPageTests(TestApiFactory api)
{
    private static readonly ReportPeriod LastWeek = new(new DateOnly(2026, 11, 2), new DateOnly(2026, 11, 9));

    private static IHtmlFormElement Form(PageResponse page, string testId) => page.FindForm(f => f.GetAttribute("data-testid") == testId, testId);

    private async Task<Guid> CreateDefinitionAsync(ApiSeed.Owner owner, params Guid[] recipients)
    {
        using var client = ApiSeed.AuthorizedClient(api, owner.Token);
        var response = await client.PostAsJsonAsync("/api/reports/definitions", new
        {
            name = "Resumen semanal", frequency = "Weekly", sections = new[] { "Headline", "Response", "AiCoverage" },
            recipients = recipients.Select(u => new { userId = u, email = true, whatsApp = false }).ToArray(),
        });
        Assert.Equal(HttpStatusCode.Created, response.StatusCode);
        return (await response.Content.ReadFromJsonAsync<ReportDefinitionResponse>())!.Id;
    }

    private async Task<Guid> GenerateAsync(Guid tenantId, Guid definitionId)
        => (await api.Services.GetRequiredService<ReportJobRunner>().GenerateAsync(tenantId, definitionId, LastWeek, DateTime.UtcNow))!.Value;

    [Fact]
    public async Task An_owner_creates_edits_and_deletes_a_report_from_the_settings_page()
    {
        var owner = await ApiSeed.RegisterOwnerAsync(api, "informes");
        using var host = WebTestHost.Create(api);
        using var session = await WebFlows.SignedInAsync(host, owner.Email);

        var list = (await session.GetAsync("/informes")).ShouldBe(HttpStatusCode.OK);
        Assert.NotNull(list.Document.QuerySelector("[data-testid=report-definitions-empty]"));
        Assert.Equal("page", list.Document.QuerySelector("nav a[href='/informes']")!.GetAttribute("aria-current"));

        var page = (await session.GetAsync("/informes/nuevo")).ShouldBe(HttpStatusCode.OK);
        Assert.Equal(6, page.Select("[data-testid=report-section] input[type=checkbox][checked]").Count());
        Assert.Contains("Meta cobra cada mensaje", page.Document.QuerySelector("[data-testid=report-whatsapp-cost]")!.TextContent);
        var form = FormModel.From(page, Form(page, "report-definition-form"))
            .Set("Name", "Resumen de los lunes").Set("Status", "active").Set("Frequency", "Weekly").Set("SendDayOfWeek", "1").Set("SendHour", "7").Set("Template", "")
            .Add("Input.Recipients[0].ByEmail", "true");
        var saved = await session.SubmitAsync(form);

        saved.ShouldRedirectTo("/informes?aviso=guardado");
        var after = (await session.FollowAsync(saved)).ShouldBe(HttpStatusCode.OK);
        Assert.NotNull(after.Document.QuerySelector("[data-testid=notice-success]"));
        var row = Assert.Single(after.Select("[data-testid=report-definition-row]"));
        Assert.Contains("Resumen de los lunes", row.TextContent);
        Assert.Contains("Semanal, los lunes a las 07:00", row.TextContent);
        var id = row.GetAttribute("data-definition-id")!;

        var edit = (await session.GetAsync($"/informes/definiciones/{id}")).ShouldBe(HttpStatusCode.OK);
        Assert.Equal("Resumen de los lunes", Form(edit, "report-definition-form").QuerySelector("input[name='Input.Name']")!.GetAttribute("value"));
        var renamed = FormModel.From(edit, Form(edit, "report-definition-form"))
            .Set("Name", "Resumen mensual").Set("Status", "paused").Set("Frequency", "Monthly").Set("SendDayOfWeek", "1").Set("SendHour", "8").Set("Template", "");
        (await session.SubmitAsync(renamed)).ShouldRedirectTo("/informes?aviso=guardado");
        var renamedRow = Assert.Single((await session.GetAsync("/informes")).Select("[data-testid=report-definition-row]"));
        Assert.Contains("Mensual, el día 1 a las 08:00", renamedRow.TextContent);
        Assert.Contains("En pausa", renamedRow.TextContent);

        var confirm = (await session.GetAsync($"/informes/definiciones/{id}")).ShouldBe(HttpStatusCode.OK);
        (await session.SubmitAsync(FormModel.From(confirm, Form(confirm, "report-delete-form")))).ShouldRedirectTo("/informes?aviso=eliminado");
        Assert.Empty((await session.GetAsync("/informes")).Select("[data-testid=report-definition-row]"));
    }

