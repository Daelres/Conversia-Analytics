    [Fact]
    public async Task The_report_page_is_readable_on_a_phone_and_by_whoever_receives_it_and_lists_the_deliveries_to_managers()
    {
        var owner = await ApiSeed.RegisterOwnerAsync(api, "informe-ver");
        var recipient = await ApiSeed.CreateMemberAsync(api, owner, "recibe");
        var outsider = await ApiSeed.CreateMemberAsync(api, owner, "ajeno");
        var reportId = await GenerateAsync(owner.TenantId, await CreateDefinitionAsync(owner, owner.UserId, recipient.UserId));
        using var host = WebTestHost.Create(api);

        using (var session = await WebFlows.SignedInAsync(host, owner.Email))
        {
            var page = (await session.GetAsync($"/informes/{reportId}")).ShouldBe(HttpStatusCode.OK);
            Assert.Contains("semana del 2 al 8 de noviembre de 2026", page.Document.QuerySelector("h1")!.TextContent);
            Assert.InRange(page.Select("[data-testid=report-indicator]").Count(), 1, 3);
            Assert.NotEmpty(page.Document.QuerySelector("[data-testid=report-diagnosis]")!.TextContent.Trim());
            Assert.InRange(page.Select("[data-testid=report-actions] li").Count(), 1, 5);
            Assert.Equal(2, page.Select("[data-testid=delivery-row]").Count());
            Assert.Contains("width=device-width", page.Body);
            Assert.Empty(page.Select("[style]"));
            Assert.Empty(SpanishUi.Leaks(SpanishUi.Extract(page)));

            var history = (await session.GetAsync("/informes")).ShouldBe(HttpStatusCode.OK);
            var row = Assert.Single(history.Select("[data-testid=report-row]"));
            Assert.Equal("Template", row.GetAttribute("data-generator"));
            Assert.Contains("Redactado automáticamente", row.TextContent);
            Assert.Contains("2 pendientes", row.TextContent);
        }

        using (var session = await WebFlows.SignedInAsync(host, recipient.Email))
        {
            var page = (await session.GetAsync($"/informes/{reportId}")).ShouldBe(HttpStatusCode.OK);
            Assert.Empty(page.Select("[data-testid=delivery-row]"));
        }

        using (var session = await WebFlows.SignedInAsync(host, outsider.Email))
        {
            var page = (await session.GetAsync($"/informes/{reportId}")).ShouldBe(HttpStatusCode.NotFound);
            Assert.Contains("Informe no encontrado", page.Text);
        }
    }

