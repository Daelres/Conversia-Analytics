using Conversia.Domain.Common;
using Conversia.Domain.Exceptions;

namespace Conversia.Domain.Entities;

/// <summary>
/// A sellable item owned by one tenant. The SKU identifies it within the tenant and never changes.
/// </summary>
public class Product : BaseEntity
{
    public const int NameMaxLength = 200;
    public const int SkuMaxLength = 50;
    public const decimal MaxPrice = 999_999_999.99m;
    public const int PriceScale = 2;

    /// <summary>
    /// The wording of each rule, the part after the subject. The request validation (<c>El campo X ...</c>) and the domain
    /// exceptions (<c>El nombre ...</c>) build their messages from these, so every layer says the same thing.
    /// </summary>
    public static readonly string NameRuleText =
        $"es obligatorio, no puede superar los {NameMaxLength} caracteres ni contener caracteres nulos (se ignoran los espacios al principio y al final)";

    public static readonly string SkuRuleText =
        $"debe tener entre 1 y {SkuMaxLength} caracteres, formados por letras, dígitos, '-' o '_' (se ignoran los espacios al principio y al final)";

    public static readonly string PriceRuleText =
        $"debe estar entre 0 y {SpanishCulture.FormatAmount(MaxPrice)}, con un máximo de {SpanishCulture.Decimals(PriceScale)}";

    public static readonly string NameRuleMessage = $"El nombre {NameRuleText}.";

    public static readonly string SkuRuleMessage = $"El SKU {SkuRuleText}.";

    public static readonly string PriceRuleMessage = $"El precio {PriceRuleText}.";

    public Guid TenantId { get; private set; }

    public string Name { get; private set; } = string.Empty;

    public string Sku { get; private set; } = string.Empty;

    public decimal Price { get; private set; }

    public int Stock { get; private set; }

    /// <summary>
    /// Optimistic-concurrency token generated by the database on every write (PostgreSQL <c>xmin</c>, the id of the transaction
    /// that last wrote the row). Never 0 for a stored row, so 0 doubles as "no valid token". The API exposes it as base64
    /// (see <c>RowVersionToken</c>).
    /// </summary>
    public uint RowVersion { get; set; }

    // Required by EF Core for materialization.
    private Product()
    {
    }

    public static Product Create(Guid tenantId, string name, string sku, decimal price, int stock)
    {
        if (tenantId == Guid.Empty)
        {
            throw new DomainException("El identificador del espacio de trabajo es obligatorio.");
        }

        var product = new Product { TenantId = tenantId, Sku = ValidateSku(sku) };
        product.ApplyDetails(name, price, stock);
        return product;
    }

    public void Update(string name, decimal price, int stock) => ApplyDetails(name, price, stock);

    /// <summary>True when the SKU, once trimmed, is 1-50 ASCII letters, digits, '-' or '_'.</summary>
    public static bool IsValidSku(string? sku)
    {
        var trimmed = sku?.Trim();
        return !string.IsNullOrEmpty(trimmed)
            && trimmed.Length <= SkuMaxLength
            && trimmed.All(c => char.IsAsciiLetterOrDigit(c) || c is '-' or '_');
    }

    /// <summary>True when the name, once trimmed, is 1-200 characters without U+0000 (PostgreSQL text cannot store it).</summary>
    public static bool IsValidName(string? name)
    {
        var trimmed = name?.Trim();
        return !string.IsNullOrEmpty(trimmed) && trimmed.Length <= NameMaxLength && !trimmed.Contains('\0');
    }

    public static bool IsValidPrice(decimal price)
        => price is >= 0 and <= MaxPrice && decimal.Round(price, PriceScale) == price;

    // Validates everything before assigning anything, so a rejected update leaves the entity untouched.
    private void ApplyDetails(string name, decimal price, int stock)
    {
        if (!IsValidName(name))
        {
            throw new DomainException(NameRuleMessage);
        }

        if (!IsValidPrice(price))
        {
            throw new DomainException(PriceRuleMessage);
        }

        if (stock < 0)
        {
            throw new DomainException("El stock no puede ser negativo.");
        }

        Name = name.Trim();
        Price = price;
        Stock = stock;
    }

    private static string ValidateSku(string sku)
    {
        if (!IsValidSku(sku))
        {
            throw new DomainException(SkuRuleMessage);
        }

        return sku.Trim();
    }
}
